function allowed(zone: ZoneRules, edge: ImportEdge): boolean {
  // Type-only edges get the runtime allowances too (intra-zone types are
  // always fine); runtime edges get only the runtime list. A zone's
  // allowance list is declared nullable but every zone sets one; coalesce
  // defensively so the declared type cannot fault the import audit.
  const runtime = zone.runtimeAllow ?? [];
  const allow = edge.kind === "runtime" ? runtime : union(runtime, zone.typeOnlyAllow);
  const isPiPackage = edge.specifier.startsWith("@earendil-works/")
    || edge.target.startsWith("node_modules/@earendil-works/");
  if (isPiPackage) return allow.includes("@earendil-works/");
  if (!edge.specifier.startsWith(".")) {
    // Bare specifier: a package import. pi packages are handled above; node
    // built-ins are policy; every other npm dependency is the zone's own.
    if (edge.specifier.startsWith("node:")) return allow.includes("node:");
    if (NODE_BUILTIN.test(edge.specifier)) return allow.includes("node:");
    return true;
  }
  // Relative specifier: resolved to a repo path — must land in an allowed tree.
  if (edge.target.startsWith("node_modules/")) {
    // Deep file imports of npm packages (allowed only where pi is).
    return allow.some((prefix) => edge.target.startsWith(prefix === "@earendil-works/" ? "node_modules/@earendil-works/" : prefix));
  }
  // A pi extension bridges to a web plugin only through that plugin's
  // contract file (web/plugins/<id>/contract.ts) — never its descriptor or
  // its client UI. Everything else under web/ stays off-limits to
  // extensions.
  if (zone.dir === "extensions" && edge.target.startsWith("web/plugins/")) {
    // A plugin's bridge contract, or the subagent-graph plugin's shared
    // publisher/projection library (the one feature several behavior
    // extensions integrate with, not a single declarative bridge).
    // A plugin's bridge contract, or the Subagent graph plugin's shared
    // projection/publisher library — the one feature several behavior
    // extensions integrate with, not a single declarative bridge.
    return edge.target.endsWith("/contract.ts")
      || edge.target.startsWith("web/plugins/subagent-graph/lib/");
  }
  return allow.some((prefix) => edge.target.startsWith(prefix));
}

test("the web↔extension boundary holds on the import graph", () => {
  const violations: string[] = [];

  for (const zone of ZONES) {
    for (const file of sourceFiles(join(process.cwd(), zone.dir), zone.skip ?? [])) {
      for (const edge of importsOf(file)) {
        if (!allowed(zone, edge)) {
          violations.push(
            `${edge.file}: ${edge.kind} import "${edge.target}" — ${zone.why}`,
          );
        }
      }
    }
  }

  assert.deepEqual(
    violations,
    [],
    "boundary violations found; the rule: web = interface, extensions = behavior (docs/web-plugin-architecture.md)",
  );
});

/**
 * AC1: a client or plugin may reach pi only through the protocol binding.
 * Imports are covered above; this catches the other side door — a literal
 * server route pasted into a component or plugin page. Every route except the
 * explicitly grandfathered transport/telemetry calls is a violation.
 */
const DIRECT_PI_ROUTE = /\/api\/(?:agent|sessions|bridge|directories|plugins\/action|plugin-manager|reload-state|client\/log)\b/;

/** Files that still own a non-capability route, and exactly which one. */
const ROUTE_EXCEPTIONS: Readonly<Record<string, readonly string[]>> = {
  "web/core/client/logging.ts": ["/api/client/log"],
  "web/core/client/protocol-client.ts": ["/api/agent/${", "/api/sessions/events"],
  "web/core/client/request-activity.ts": ["/api/agent/"],
  "web/core/client/new-session-dialog.tsx": ["/api/directories"],
  "web/core/client/plugin-system/actionClient.ts": ["/api/plugins/action"],
};

function directRouteViolations(file: string, text: string): string[] {
  const allowed = ROUTE_EXCEPTIONS[file] ?? [];
  const violations: string[] = [];
  for (const [index, line] of text.split("\n").entries()) {
    const match = line.match(DIRECT_PI_ROUTE)?.[0];
    if (match !== undefined && !allowed.some((prefix) => line.includes(prefix))) {
      violations.push(`${file}:${index + 1} ${match}`);
    }
  }
  return violations;
}

test("a direct pi route in client or plugin code is detected", () => {
  assert.deepEqual(
    directRouteViolations("web/core/client/example.tsx", 'void fetch("/api/agent/abc/history");'),
    ["web/core/client/example.tsx:1 /api/agent"],
  );
  assert.deepEqual(
    directRouteViolations("web/core/client/protocol-client.ts", 'void fetch("/api/agent/abc/history");'),
    ["web/core/client/protocol-client.ts:1 /api/agent"],
  );
});

test("the client and plugins never call undeclared pi routes directly", () => {
  const offenders: string[] = [];
  for (const dir of ["web/core/client", "web/plugins"]) {
    for (const file of sourceFiles(join(process.cwd(), dir), ["web/plugins/subagent-graph"])) {
      offenders.push(...directRouteViolations(relative(process.cwd(), file), readFileSync(file, "utf8")));
    }
  }
  assert.deepEqual(offenders, [], `direct pi routes belong behind the protocol binding:\n  ${offenders.join("\n  ")}`);
});

test("migrated panels self-register from plugin-owned browser halves", () => {
  const app = readFileSync(join(process.cwd(), "web", "app.tsx"), "utf8");
  const routes = readFileSync(join(process.cwd(), "web", "core", "server", "routes.ts"), "utf8");
  assert.equal(routes.includes("/api/agent/:id/pi_api"), false, "the pi_api route alias must be retired");
  assert.equal(app.includes('import "./plugins/panels.tsx"'), false, "the composition root must not import the old plugin panel list");
  assert.match(app, /mountPluginBrowserHalves/, "the composition root must mount plugin-owned halves");
  for (const name of ["files", "artifacts", "router"]) {
    const half = join(process.cwd(), "web", "plugins", name, "browser", "index.ts");
    const source = readFileSync(half, "utf8");
    assert.match(source, /registerPluginPanel/, `${name} must register its own panel`);
  }
});
